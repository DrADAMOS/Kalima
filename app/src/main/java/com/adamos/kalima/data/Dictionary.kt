    private val enrichedAnswers = emptyList<String>()
    private val enrichedGuesses = emptyList<String>()

    private val runtimeRemoteWords = mutableSetOf<String>()

    fun init(context: Context) {
        try {
            val inputStream = context.assets.open("remote-dictionary-v1.json")
            val jsonStr = inputStream.bufferedReader(Charsets.UTF_8).use { it.readText() }
            val regex = "\"([\\u0621-\\u064A\\u0629\\u0649]{3,8})\"".toRegex()
            regex.findAll(jsonStr).forEach { match ->
                runtimeRemoteWords.add(normalize(match.groupValues[1]))
            }
        } catch (_: Exception) {}
    }

    private val jvmRemoteWords: Set<String> by lazy {
        val set = mutableSetOf<String>()
        val candidates = listOf(
            java.io.File("dictionary/remote-dictionary-v1.json"),
            java.io.File("../dictionary/remote-dictionary-v1.json"),
            java.io.File("app/../dictionary/remote-dictionary-v1.json"),
            java.io.File("../../dictionary/remote-dictionary-v1.json")
        )
        for (file in candidates) {
            try {
                if (file.exists()) {
                    val jsonStr = file.readText(Charsets.UTF_8)
                    val regex = "\"([\\u0621-\\u064A\\u0629\\u0649]{3,8})\"".toRegex()
                    regex.findAll(jsonStr).forEach { match ->
                        set.add(normalize(match.groupValues[1]))
                    }
                    break
                }
            } catch (_: Exception) {}
        }
        set
    }

    private val allWords: List<String> = baseWords + enrichedAnswers
    private val extraGuesses: List<String> = baseGuesses + enrichedGuesses

    /**
     * الكلمات المعروضة تحتفظ بتهجئتها العربية الأصلية (مثل مدرسة لا مدرسه).
     * التطبيع مخصص للمقارنة فقط، حتى لا تتحول التاء المربوطة في واجهة اللعبة.
     */
    private val answerWords: List<String> = allWords
        .map { it.trim() }
        .filter { word ->
            val normalized = normalize(word)
            normalized.length in 3..8 && normalized.all { ch -> ch.isArabicLetter() }
        }
        .distinctBy { normalize(it) }

    /** مجموعة مطبّعة للمقارنة وقبول التخمينات */
    private val knownWords: Set<String> = answerWords.map { normalize(it) }.toSet()

    /** كلمات الإجابات مجمَّعة حسب طولها مع الحفاظ على الإملاء الصحيح */
    private val words: Map<Int, List<String>> = answerWords
        .groupBy { normalize(it).length }
        .mapValues { (_, list) -> list.sorted() }
        .toSortedMap()

    /**
     * كل ما يُقبل كتخمين: الإجابات + قائمة التخمينات الإضافية.
     * أوسع من knownWords بكثير، ولا يؤثر على اختيار كلمة الجولة.
     */
    private val guessableWords: Set<String> =
        (knownWords + extraGuesses.map { normalize(it.trim()) })
            .filter { it.length in 3..8 && it.all { ch -> ch.isArabicLetter() } }
            .toSet()

    /** أطوال الكلمات المتاحة كإجابات */
    val lengths: List<Int> = words.keys.sorted()

    private val blockedWords = setOf(
        "حرب", "دم", "موت", "سجن", "قتل", "ضرب", "جرح",
        "ظلم", "خوف", "كره", "فناء", "عدم",
    )

    /** تطبيع الحروف: أ إ آ ← ا، ة ← ه */
    fun normalize(text: String): String = buildString(text.length) {
        for (i in 0 until text.length) {
            when (val c = text[i]) {
                'أ', 'إ', 'آ' -> append('ا')
                'ة' -> append('ه')
                else -> append(c)
            }
        }
    }

    /**
     * هل الكلمة آمنة للوضع الآمن؟
     * المطابقة على الكلمة كاملةً بعد التطبيع — لا على سلسلة فرعية —
     * لأن "دم" داخل "قدم" أو "ندم" ليس محتوى غير لائق.
     */
    fun isSafe(word: String): Boolean {
        val normalized = normalize(word.trim())
        if (normalized in blockedWords) return false
        return normalized.split(' ').none { it in blockedWords }
    }

    /** هل الكلمة من قائمة الإجابات؟ */
    fun isKnownWord(word: String): Boolean = normalize(word.trim()) in knownWords

    /** هل تُقبل الكلمة كتخمين؟ (أوسع بكثير من isKnownWord) */
    fun isGuessable(word: String): Boolean {
        val norm = normalize(word.trim())
        return norm in guessableWords || norm in jvmRemoteWords || norm in runtimeRemoteWords
    }

    /**
     * كلمة عشوائية بطول محدد من قائمة الإجابات.
     * @param onlySafe تصفية الكلمات المناسبة للأطفال
     */
    fun randomWord(length: Int, onlySafe: Boolean = false, random: Random = Random.Default): String {
        val pool = poolFor(length, onlySafe)
        return pool[random.nextInt(pool.size)]
    }

    /** قائمة الإجابات المتاحة بطول معين، بتهجئتها العربية الصحيحة. */
    fun wordsForLength(length: Int, onlySafe: Boolean = false): List<String> =
        poolFor(length, onlySafe).toList()

    /**
     * كلمة اليوم — ثابتة لنفس التاريخ والطول.
     * يعطي نفس الكلمة لكل اللاعبين في نفس اليوم.
     */
    fun dailyWord(length: Int, dateKey: String, onlySafe: Boolean = false): String {
        val pool = poolFor(length, onlySafe)
        val seed = dateKey.hashCode() + length * 31
        return pool[Random(seed).nextInt(pool.size)]
    }

    fun dailyWordForDate(length: Int, dateKey: String, onlySafe: Boolean = false): String =
        dailyWord(length, dateKey, onlySafe)

    private fun poolFor(length: Int, onlySafe: Boolean): List<String> {
        val base = words[length]
            ?: throw IllegalArgumentException(
                "لا توجد كلمات بطول $length — الأطوال المتاحة: $lengths"
            )
        val filtered = if (onlySafe) base.filter { isSafe(it) } else base
        return filtered.ifEmpty { base }
    }

    /**
     * هل النص حروف عربية بطول صحيح؟
     * لا تفحص وجود الكلمة في القاموس — انظر isGuessable لذلك.
     */
    fun isValidGuess(guess: String): Boolean =
        guess.length in 3..8 && guess.all { it.isArabicLetter() }

    private fun Char.isArabicLetter(): Boolean =
        this in '\u0621'..'\u064A' || this == '\u0629' || this == '\u0649'
