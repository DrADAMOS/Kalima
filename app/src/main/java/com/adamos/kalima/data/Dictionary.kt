    private val runtimeRemoteWords: MutableSet<String> = java.util.concurrent.ConcurrentHashMap.newKeySet()
    private val runtimeBlockedWords: MutableSet<String> = java.util.concurrent.ConcurrentHashMap.newKeySet()

    val isReady: Boolean get() = runtimeRemoteWords.isNotEmpty() || knownWords.isNotEmpty()

    fun init(context: Context) {
        loadBlockedWordsAsset(context)
        try {
            val jsonStr = context.assets.open("remote-dictionary-v1.json")
                .bufferedReader(Charsets.UTF_8).use { it.readText() }
            val root = org.json.JSONObject(jsonStr)
            if (root.optInt("schemaVersion", -1) != 1) return
            addSnapshotArray(root.optJSONArray("answers"), runtimeRemoteWords)
            addSnapshotArray(root.optJSONArray("guesses"), runtimeRemoteWords)
            loadExpandedGuessAsset(context)
        } catch (e: Exception) {
            android.util.Log.w("KalimaDictionary", "Could not load bundled dictionary snapshot", e)
        }
    }

    private fun loadBlockedWordsAsset(context: Context) {
        try {
            context.assets.open("blocked-words.txt").bufferedReader(Charsets.UTF_8).useLines { lines ->
                lines.forEach { line ->
                    val norm = normalize(line.trim())
                    if (norm.isNotEmpty()) runtimeBlockedWords.add(norm)
                }
            }
        } catch (e: Exception) {
            android.util.Log.w("KalimaDictionary", "Could not load blocked-words.txt asset", e)
        }
    }

    private fun loadExpandedGuessAsset(context: Context) {
        try {
            context.assets.open("arabic-guess-words.txt").bufferedReader(Charsets.UTF_8).useLines { lines ->
                lines.forEach { raw ->
                    val word = raw.trim()
                    if (isValidGuess(word) && isPlausibleExpandedEntry(word)) runtimeRemoteWords.add(normalize(word))
                }
            }
        } catch (e: java.io.IOException) {
            android.util.Log.w("KalimaDictionary", "Expanded offline word list is unavailable", e)
        }
    }

    internal fun isPlausibleExpandedEntry(word: String): Boolean {
        val normalized = normalize(word)
        if (normalized.length !in 3..8) return false
        if (normalized.toSet().size <= 1) return false
        if (normalized.windowed(3).any { it[0] == it[1] && it[1] == it[2] }) return false
        val undoubleable = setOf('ا', 'ى', 'ة', 'ء', 'ؤ', 'ئ')
        for (i in 0 until normalized.length - 1) {
            if (normalized[i] == normalized[i + 1] && normalized[i] in undoubleable) return false
        }
        val hamzaIdx = normalized.indexOf('ء')
        if (hamzaIdx >= 0) {
            if (hamzaIdx == 0) return false
            if (normalized.indexOf('ء', hamzaIdx + 1) >= 0) return false
            val isEnd = hamzaIdx == normalized.length - 1
            val prevChar = normalized[hamzaIdx - 1]
            val isPrecededByValidChar = prevChar in setOf('ا', 'و', 'ي', 'ف', 'ب', 'د', 'ز', 'ر', 'ك', 'ن', 'ل', 'ط', 'ث')
            if (!isEnd && !isPrecededByValidChar) return false
        }
        return true
    }

    private fun addSnapshotArray(array: org.json.JSONArray?, destination: MutableSet<String>) {
        if (array == null) return
        for (index in 0 until minOf(array.length(), 100_000)) {
            val word = array.optString(index, "").trim()
            if (isValidGuess(word)) destination.add(normalize(word))
        }
    }

    fun applyOnlineWords(words: Collection<String>) {
        words.asSequence()
            .map { it.trim() }
            .filter { isValidGuess(it) }
            .map { normalize(it) }
            .forEach { runtimeRemoteWords.add(it) }
    }

    private val jvmRemoteWords: Set<String> by lazy {
        val set = mutableSetOf<String>()
        val isAndroidRuntime = try {
            Class.forName("android.os.Build")
            true
        } catch (_: ClassNotFoundException) {
            false
        }
        if (isAndroidRuntime) return@lazy set
        val candidates = listOf(
            java.io.File("dictionary/remote-dictionary-v1.json"),
            java.io.File("../dictionary/remote-dictionary-v1.json"),
            java.io.File("app/../dictionary/remote-dictionary-v1.json"),
            java.io.File("../../dictionary/remote-dictionary-v1.json")
