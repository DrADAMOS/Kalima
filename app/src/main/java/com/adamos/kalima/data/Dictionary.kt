                    break
                }
            } catch (_: Exception) {
                // Try the next known repository-relative location.
            }
        }
        set
    }

    private val allWords: List<String> = baseWords + enrichedAnswers
    private val extraGuesses: List<String> = baseGuesses + enrichedGuesses

    private val answerWords: List<String> = allWords
        .map { it.trim() }
        .filter { word ->
            val normalized = normalize(word)
            normalized.length in 3..8 && normalized.all { ch -> ch.isArabicLetter() }
