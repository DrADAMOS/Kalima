    private val blockedWords = setOf(
        "خمر", "حشيش", "زنا", "عنف", "سم", "سلاح", "سرقة", "خيانة", "غدر",
        "مخدرات", "سحر", "قمار", "خمرة", "نبيذ", "مسكر", "سجاير", "هيروين", "كوكايين"
